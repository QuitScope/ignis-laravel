// Regenerates resources/js/lib/tileIconMap.ts (deterministic; output is sorted).
// Run from the repo root:  node scripts/generate-tile-icons.mjs [path/to/fa-free-icons.json]
// Default input: ../ignis/assets/json/fa-free-icons.json (legacy checkout next to this repo).
// Map = every Font Awesome free name that exists under the same name in Lucide (kebab -> PascalCase) + the hand-picked aliases below.
import { readFileSync, writeFileSync } from 'node:fs';
import * as lucide from '@lucide/vue';

const input = process.argv[2] ?? '../ignis/assets/json/fa-free-icons.json';
const out = 'resources/js/lib/tileIconMap.ts';

// FA name (no "fa-" prefix) -> Lucide export. Aliases of FA 5 and 6 share one Lucide icon; these win over the same-name rule.
const aliases = {
    'up-right-from-square': 'ExternalLink', 'arrow-up-right-from-square': 'ExternalLink', 'external-link-alt': 'ExternalLink', 'external-link': 'ExternalLink',
    home: 'House', 'boxes-stacked': 'Boxes', boxes: 'Boxes', 'clock-rotate-left': 'History', history: 'History', 'diagram-project': 'Workflow',
    'file-lines': 'FileText', 'file-alt': 'FileText', 'file-medical': 'FileHeart', fire: 'Flame', 'id-badge': 'IdCard', 'kit-medical': 'BriefcaseMedical',
    'layer-group': 'Layers', 'puzzle-piece': 'Puzzle', 'screwdriver-wrench': 'Wrench', sliders: 'SlidersHorizontal', 'table-cells-large': 'LayoutGrid',
    'triangle-exclamation': 'TriangleAlert', 'exclamation-triangle': 'TriangleAlert', 'truck-medical': 'Ambulance', 'user-shield': 'ShieldUser',
    'shield-halved': 'ShieldHalf', discord: 'MessageCircle', comments: 'MessageCircle', 'calendar-days': 'Calendar', 'folder-open': 'Folder',
    envelope: 'Mail', 'location-dot': 'MapPin', 'clipboard-list': 'ClipboardList', gear: 'Settings', cog: 'Settings', 'chart-line': 'ChartLine',
    'walkie-talkie': 'Radio', 'tower-broadcast': 'RadioTower', 'satellite-dish': 'Satellite', 'circle-info': 'Info', link: 'Link2', 'book-open': 'BookOpen',
};

const pascal = (n) => n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const names = [...new Set(JSON.parse(readFileSync(input, 'utf8')).map((c) => c.split(/\s+/).pop().replace(/^fa-/, '')))];
const map = {};
for (const n of names) if (/^[a-z][a-z0-9-]*$/.test(n) && pascal(n) in lucide) map[n] = pascal(n);
Object.assign(map, aliases);
for (const [k, v] of Object.entries(map)) if (!(v in lucide)) throw new Error(`${k}: no Lucide icon ${v}`);

const keys = Object.keys(map).sort();
const used = [...new Set(Object.values(map))].sort();
const q = (k) => (/^[a-z]+$/.test(k) ? k : `'${k}'`);
writeFileSync(out, `// GENERATED by scripts/generate-tile-icons.mjs - do not edit by hand.
import { ${used.join(', ')}, type LucideIcon } from '@lucide/vue';

export default {
${keys.map((k) => `    ${q(k)}: ${map[k]},`).join('\n')}
} as Record<string, LucideIcon>;
`);
console.log(`${keys.length} icons -> ${out}`);
